<#
.SYNOPSIS
  Derives a build version from git and writes the generated version artifacts
  consumed by every component (C# exe, the two C++ DLLs, the WiX MSI).

  Versioning scheme
  -----------------
  Tagged release (tag like v1.2.3, N commits after it):
      1.2.3.N        FileVersion / native FILEVERSION
      1.2.3          MSI ProductVersion
      1.2.0.0        AssemblyVersion (kept coarse so references don't rebind every commit)
  No tag yet (K = total commit count):
      0.1.K.0  /  0.1.K  /  0.1.0.0
  No git at all:
      0.0.0 everywhere, informational "0.0.0-nogit".

  Outputs (all git-ignored, regenerated each build):
      build/Version.g.cs      -> C# assembly attributes
      build/Version.g.h       -> native VERSIONINFO macros (included by the .rc files)
      Setup/Version.g.wxi     -> WiX preprocessor define $(BuildVersion)

  Run standalone or from MSBuild (build/GitVersion.targets). Never throws: on any
  failure it still emits a valid 0.0.0 fallback so the build is never blocked.
#>
[CmdletBinding()]
param()

$ErrorActionPreference = 'Continue'

$buildDir = $PSScriptRoot
$root = Split-Path -Parent $buildDir

function Invoke-Git {
    param([string[]]$GitArgs)
    try {
        $out = & git -C $root @GitArgs 2>$null
        if ($LASTEXITCODE -eq 0) { return ($out | Out-String).Trim() }
    } catch { }
    return $null
}

function Clamp([int]$v) {
    if ($v -lt 0) { return 0 }
    if ($v -gt 65534) { return 65534 }
    return $v
}

$major = 0; $minor = 0; $patch = 0; $build = 0; $info = '0.0.0-nogit'

$describe = Invoke-Git @('describe', '--tags', '--long', '--dirty')
if ($describe -and ($describe -match '^v?(\d+)\.(\d+)\.(\d+)-(\d+)-g[0-9a-f]+(-dirty)?$')) {
    # Tagged build.
    $major = [int]$Matches[1]
    $minor = [int]$Matches[2]
    $patch = [int]$Matches[3]
    $build = [int]$Matches[4]
    $info  = $describe
}
else {
    # No usable tag: base 0.1, patch = total commit count so it changes per commit.
    $count = Invoke-Git @('rev-list', '--count', 'HEAD')
    $sha   = Invoke-Git @('rev-parse', '--short', 'HEAD')
    if ($count -and ($count -match '^\d+$')) {
        $major = 0; $minor = 1; $patch = [int]$count; $build = 0
        $dirty = ''
        $status = Invoke-Git @('status', '--porcelain')
        if ($status) { $dirty = '-dirty' }
        if ($sha) { $info = "0.1.$count+g$sha$dirty" } else { $info = "0.1.$count$dirty" }
    }
    # else: leave the 0.0.0-nogit fallback.
}

$major = Clamp $major; $minor = Clamp $minor; $patch = Clamp $patch; $build = Clamp $build

$asmVersion  = "$major.$minor.0.0"
$fileVersion = "$major.$minor.$patch.$build"
$msiVersion  = "$major.$minor.$patch"

$nl = "`r`n"

$csContent = @"
// <auto-generated>
//   Generated by build/Set-GitVersion.ps1 from git. Do not edit; do not commit.
// </auto-generated>
using System.Reflection;

[assembly: AssemblyVersion("$asmVersion")]
[assembly: AssemblyFileVersion("$fileVersion")]
[assembly: AssemblyInformationalVersion("$info")]
"@ -replace "`r?`n", $nl

$hContent = @"
#pragma once
// Generated by build/Set-GitVersion.ps1 from git. Do not edit; do not commit.
#define VER_FILEVERSION        $major,$minor,$patch,$build
#define VER_FILEVERSION_STR    "$fileVersion\0"
#define VER_PRODUCTVERSION     $major,$minor,$patch,$build
#define VER_PRODUCTVERSION_STR "$info\0"
"@ -replace "`r?`n", $nl

$wxiContent = @"
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by build/Set-GitVersion.ps1 from git. Do not edit; do not commit. -->
<Include>
  <?define BuildVersion = "$msiVersion" ?>
  <?define BuildVersionFull = "$fileVersion" ?>
</Include>
"@ -replace "`r?`n", $nl

function Write-IfChanged {
    param([string]$Path, [string]$Content)
    try {
        if (Test-Path -LiteralPath $Path) {
            $existing = [System.IO.File]::ReadAllText($Path)
            if ($existing -eq $Content) { return }
        }
        $enc = New-Object System.Text.UTF8Encoding($false)  # no BOM (RC-friendly)
        $tmp = "$Path.$PID.tmp"
        [System.IO.File]::WriteAllText($tmp, $Content, $enc)
        Move-Item -LiteralPath $tmp -Destination $Path -Force
    } catch {
        # A racing parallel build may have written it already; ignore.
    }
}

# Trailing newline: the RC compiler errors (RC1004) on a header without one.
Write-IfChanged -Path (Join-Path $buildDir 'Version.g.cs') -Content ($csContent + $nl)
Write-IfChanged -Path (Join-Path $buildDir 'Version.g.h')  -Content ($hContent + $nl)
Write-IfChanged -Path (Join-Path $root 'Setup\Version.g.wxi') -Content ($wxiContent + $nl)

Write-Host "GitVersion: file=$fileVersion msi=$msiVersion asm=$asmVersion info=$info"
